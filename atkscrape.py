def read_pages(filename):
    pages = []
    with open(filename,'r') as f:
        for line in f:
            line = line.strip()
            if not line or line[0] == "#":
                continue
            pages.append(line)
    return pages

def str2bool(value):
    """argparse type for True/False style options."""
    if isinstance(value, bool):
        return value
    if value.lower() in ('yes', 'true', 't', 'y', '1'):
        return True
    if value.lower() in ('no', 'false', 'f', 'n', '0'):
        return False
    raise ValueError("expected True or False, got " + value)

def get_password(password):
    """Use the password given, else $ATK_PASSWORD, else prompt for it without echoing."""
    if password:
        return password
    if os.environ.get('ATK_PASSWORD'):
        return os.environ['ATK_PASSWORD']
    import getpass
    return getpass.getpass("ATK password: ")

def create_driver(path=None, chrome_binary=None, headless=True):
    """
    Start Chrome via Selenium.

    path:          path to a chromedriver matching your installed Chrome. If it is
                   None or does not exist, Selenium Manager (selenium >= 4.11) finds
                   or downloads the right driver automatically.
    chrome_binary: optional path to the Chrome/Chromium executable to use.
    """
    print('Starting...')
    try:
        chrome_options = Options()
        if headless:
            chrome_options.add_argument('--headless=new')
        chrome_options.add_argument('--window-size=1920,1080')
        chrome_options.add_argument('--hide-scrollbars')
        chrome_options.add_argument('--no-sandbox')
        chrome_options.add_argument('--disable-dev-shm-usage')
        # ATK serves a reduced page to the default headless user agent
        chrome_options.add_argument(
            '--user-agent=Mozilla/5.0 (Windows NT 10.0; Win64; x64) AppleWebKit/537.36 '
            '(KHTML, like Gecko) Chrome/130.0.0.0 Safari/537.36')
        chrome_options.add_experimental_option(
            'excludeSwitches', ['enable-logging'])
        if chrome_binary:
            chrome_options.binary_location = chrome_binary
        if path and os.path.exists(path):
            service = Service(path)
        else:
            if path:
                print("chromedriver not found at " + path + ", letting Selenium find one")
            service = Service()
        driver = webdriver.Chrome(service=service, options=chrome_options)
        return driver
    except Exception as e:
        print("Couldn't create chrome driver")
        print(e)
        exit(1)

SIGN_IN_URL = "https://www.americastestkitchen.com/sign_in"

def login(driver, email, password):
    print("Logging in")
    try:
        driver.get(SIGN_IN_URL)
        wait = WebDriverWait(driver, timeout=30)
        # The site's element ids are randomly generated by React on every load, so
        # locate the form fields by their (stable) type attributes instead.
        form_css = 'form[aria-label="sign in form"]'
        e = wait.until(EC.element_to_be_clickable(
            (By.CSS_SELECTOR, form_css + ' input[type="email"]')))
        close_popups(driver)
        e.clear()
        e.send_keys(email)
        e = driver.find_element(By.CSS_SELECTOR, form_css + ' input[type="password"]')
        e.clear()
        e.send_keys(password)
        e = driver.find_element(
            By.CSS_SELECTOR, form_css + ' button[data-testid="Button-primary"], ' + form_css + ' button[type="submit"]')
        driver.execute_script("arguments[0].click();", e)
        wait = WebDriverWait(driver, timeout=60)
        wait.until(lambda d: not d.current_url.startswith(SIGN_IN_URL)
                   or login_error(d) is not None)
        err = login_error(driver)
        if err is not None and driver.current_url.startswith(SIGN_IN_URL):
            raise Exception("Sign in rejected: " + err)
        print("Logged in")
    except Exception as e:
        print("Couldn't log in")
        print(e)
        exit(1)

def login_error(driver):
    """Return the sign-in form's error text, or None if there is none."""
    for el in driver.find_elements(
            By.CSS_SELECTOR, 'form[aria-label="sign in form"] [role="alert"], '
                             'form[aria-label="sign in form"] [id^="error-label-"]'):
        text = el.text.strip()
        if text:
            return text
    return None

def close_popups(driver):
    """Dismiss cookie banners / marketing pop-ups that can block clicks."""
    for css in ['button[aria-label="Close Banner"]', '.bx-close-link', '.bx-button',
                'button.osano-cm-accept-all', 'button.osano-cm-dialog__close']:
        for el in driver.find_elements(By.CSS_SELECTOR, css):
            try:
                if el.is_displayed():
                    el.click()
            except Exception:
                pass

def trim(im):
    # trims empty around image (based on color of upper left pixel)
    bg = Image.new(im.mode, im.size, im.getpixel((0, 0)))
    diff = ImageChops.difference(im, bg)
    diff = ImageChops.add(diff, diff)
    bbox = diff.getbbox()
    if bbox:
        return im.crop(bbox)
    else:
        return im

def format_images(path):
    # trims images and adds equal border around each, saves to new folder
    images = glob.glob(path+'/'+'*.png')
    curr = 1

    print('Trimming...')

    for image in images:
        base = basename(image)
        newname = splitext(base)[0]+'.trimmed.png'
        print(base+" -> "+newname)
        im = Image.open(image)
        border = (0, 209, 0, 0)  # left, up, right, bottom (209 = site header)
        try:
            im = ImageOps.crop(im, border)
            color = im.getpixel((0, 0))
            im = trim(im)
            im = ImageOps.expand(im, 50, color)
            im.save(path+'/'+newname)
        except Exception as e:
            print(e)
        curr += 1

def make_image(driver, slug, savepath):
    """
    Saves a screenshot of the full recipe page to savepath/slug.png
    """
    try:
        # Get the pixel height of the page content for the screenshot
        total_height = driver.execute_script(
            "return Math.max(document.body.scrollHeight, document.documentElement.scrollHeight);")
        # Set chrome window to 1920 x content height
        driver.set_window_size(1920, total_height)  # the trick
        time.sleep(2)
        driver.save_screenshot(os.path.join(savepath, slug + ".png"))
    except Exception as e:
        print(e)

def _cls(pattern):
    """
    Match a CSS-module class name. ATK's class names look like
    'Ingredients-module-scss-module__IAxgzG__ingredient'; the hash in the middle
    changes whenever the site is rebuilt, so match on the stable parts only.
    """
    return re.compile(pattern)

def _text(el, sep=" "):
    """Visible text of an element with whitespace normalised."""
    if el is None:
        return ""
    return re.sub(r'\s+', ' ', el.get_text(sep, strip=True)).strip()

def _iso_duration_to_text(value):
    """Turn an ISO 8601 duration such as 'PT1H30M' into '1 hour 30 minutes'."""
    m = re.match(r'^P(?:(\d+)D)?(?:T(?:(\d+)H)?(?:(\d+)M)?(?:(\d+)S)?)?$', value or "")
    if not m or not any(m.groups()):
        return value or ""
    parts = []
    for amount, unit in zip(m.groups(), ["day", "hour", "minute", "second"]):
        if amount and int(amount):
            n = int(amount)
            parts.append("{0} {1}{2}".format(n, unit, "" if n == 1 else "s"))
    return " ".join(parts)

def _find_recipe_ld(soup):
    """Return the schema.org Recipe object embedded in the page as JSON-LD (or {})."""
    for tag in soup.find_all('script', attrs={'type': 'application/ld+json'}):
        try:
            data = json.loads(tag.string or "")
        except ValueError:
            continue
        stack = data if isinstance(data, list) else [data]
        while stack:
            item = stack.pop(0)
            if isinstance(item, list):
                stack.extend(item)
                continue
            if not isinstance(item, dict):
                continue
            types = item.get('@type')
            types = types if isinstance(types, list) else [types]
            if 'Recipe' in types:
                return item
            if '@graph' in item:
                stack.extend(item['@graph'])
    return {}

def _ld_steps(instructions, section=None):
    """Flatten schema.org recipeInstructions (steps and sections) to (section, text) pairs."""
    steps = []
    if isinstance(instructions, str):
        return [(section, s.strip()) for s in instructions.split('\n') if s.strip()]
    for item in instructions or []:
        if isinstance(item, str):
            steps.append((section, item.strip()))
        elif item.get('@type') == 'HowToSection':
            name = (item.get('name') or "").strip().rstrip(':')
            steps.extend(_ld_steps(item.get('itemListElement'), name or section))
        else:
            text = item.get('text') or item.get('name') or ""
            if text.strip():
                steps.append((section, re.sub(r'\s+', ' ', text).strip()))
    return steps

def parse_recipe(html, url=""):
    """
    Parse an ATK / Cook's Country / Cook's Illustrated recipe page.

    Returns (recipe_dict, image_url). recipe_dict is in mealie format.

    Most data comes from the schema.org Recipe JSON-LD the site embeds for search
    engines, which is far more stable than the page markup. The page markup is
    used only for what JSON-LD lacks (ingredient group headings, the "Why This
    Recipe Works" text, and the displayed total time).
    """
    soup = BeautifulSoup(html, 'html.parser')
    ld = _find_recipe_ld(soup)

    # TITLE
    title = (ld.get('name') or "").strip()
    if not title:
        title = _text(soup.find('h1'))

    # DESCRIPTION: prefer "Why This Recipe Works", fall back to the short headnote
    description = ""
    why = soup.find(['h2', 'h3'], string=re.compile(r'^\s*Why This (Recipe )?Works\s*$', re.I))
    if why is not None:
        paras = [_text(p) for p in why.parent.find_all('p')]
        description = " ".join(p for p in paras if p and p.lower() not in ("read more", "read less"))
    if not description:
        description = re.sub(r'\s+', ' ', ld.get('description') or "").strip()

    # TAGS
    tags = []
    for key in ('recipeCategory', 'recipeCuisine', 'keywords'):
        value = ld.get(key) or []
        if isinstance(value, str):
            value = value.split(',')
        for tag in value:
            tag = tag.strip()
            if tag and tag not in tags:
                tags.append(tag)

    # IMAGE
    image_url = None
    image = ld.get('image')
    if isinstance(image, list):
        image = image[0] if image else None
    if isinstance(image, dict):
        image = image.get('url') or image.get('contentUrl')
    if isinstance(image, str) and image.startswith('http'):
        image_url = image
    else:
        og = soup.find('meta', attrs={'property': 'og:image'})
        if og is not None and (og.get('content') or "").startswith('http'):
            image_url = og['content']

    # TIME / YIELD
    totaltime = ""
    recipeyield = ""
    for card in soup.find_all('div', class_=_cls(r'TimeAndYield-module.*__card$')):
        heading = _text(card.find(['h3', 'h4']))
        value = _text(card.find('span'))
        if re.search(r'time', heading, re.I) and not totaltime:
            totaltime = value
        elif re.search(r'yield|serves|makes', heading, re.I) and not recipeyield:
            recipeyield = value
    if not totaltime:
        totaltime = _iso_duration_to_text(ld.get('totalTime'))
    if not recipeyield:
        ry = ld.get('recipeYield') or ""
        recipeyield = ry[0] if isinstance(ry, list) and ry else (ry if isinstance(ry, str) else str(ry))

    # INGREDIENTS: list of (group title or None, text)
    ingredients = []
    # The page renders the ingredient list several times (desktop, mobile, side
    # drawer); use the first copy only.
    container = soup.find('div', class_=_cls(r'Ingredients-module.*__container$'))
    if container is not None:
        for group in container.find_all('fieldset'):
            group_title = None
            legend = group.find('legend')
            if legend is not None:
                legend = legend.__copy__()
                for hidden in legend.find_all(class_=_cls(r'[Vv]isuallyHidden')):
                    hidden.decompose()
                group_title = _text(legend) or None
            for item in group.find_all('div', class_=_cls(r'Ingredients-module.*__ingredient$')):
                text = _text(item)
                if text:
                    ingredients.append((group_title, text))
    if not ingredients:
        ingredients = [(None, re.sub(r'\s+', ' ', i).strip())
                       for i in ld.get('recipeIngredient') or [] if i.strip()]

    # STEPS: list of (section title or None, text)
    steps = _ld_steps(ld.get('recipeInstructions'))
    if not steps:
        container = soup.find(class_=_cls(r'instructions-module.*__instructionsList$'))
        section = None
        if container is not None:
            for wrapper in container.find_all('div', class_=_cls(r'instructions-module.*__instructionWrapper$')):
                name = wrapper.find(class_=_cls(r'instructions-module.*__instructionName$'))
                if name is not None:
                    section = _text(name)
                for li in wrapper.find_all('li'):
                    if _text(li):
                        steps.append((section, _text(li)))

    recipe = {}
    recipe["name"] = title
    recipe["description"] = description
    recipe["tags"] = tags
    recipe["totalTime"] = totaltime
    recipe["recipeYield"] = recipeyield

    # mealie shows an ingredient's title as a heading above it, so only set it on
    # the first ingredient of each group
    i = []
    previous = None
    for group_title, text in ingredients:
        i.append({"title": group_title if group_title != previous else None,
                  "note": text,
                  "referenceId": str(uuid.uuid4()),
                  "disableAmount": True,
                  "quantity": 1})
        previous = group_title
    recipe["recipeIngredient"] = i

    s = []
    previous = None
    for section, text in steps:
        step = {"text": text, "id": str(uuid.uuid4()), "ingredientReferences": []}
        if section and section != previous:
            step["title"] = section.capitalize()
        s.append(step)
        previous = section
    recipe["recipeInstructions"] = s

    recipe["org_url"] = (ld.get('url') or url)
    recipe["settings"] = {
        "public": True,
        "showNutrition": False,
        "showAssets": True,
        "landscapeView": True,
        "disableComments": False,
        "disableAmount": True
    }
    return (recipe, image_url)

def make_json(driver):
    """
    Returns (dictionary of recipe in mealie-formatting, image bytes or None)
    """
    WebDriverWait(driver, 30).until(
        EC.presence_of_element_located((By.CSS_SELECTOR, 'h1')))
    # Give the client-side app a moment to finish rendering the recipe body
    try:
        WebDriverWait(driver, 10).until(
            EC.presence_of_element_located((By.CSS_SELECTOR, '[data-ingredients-container]')))
    except TimeoutException:
        pass

    recipe, image_url = parse_recipe(driver.page_source, driver.current_url)
    if not recipe["recipeIngredient"] and not recipe["recipeInstructions"]:
        print("  Warning: no ingredients or instructions found on " + driver.current_url)

    img_handle = None
    if image_url:
        try:
            r = requests.get(image_url, timeout=30, headers={'Accept': 'image/jpeg,image/*'})
            r.raise_for_status()
            img_handle = r.content
        except Exception as e:
            print("  Couldn't download image: " + str(e))
    return (recipe, img_handle)

def save_one_recipe(driver, recipe, do_image, do_json, savepath):
    page = recipe
    slug = basename(page.split('?')[0].split('#')[0].rstrip('/'))
    try: # Load the recipe
        driver.get(page)
    except Exception as e:
        print(e)

    if do_json:
        recipe, img = make_json(driver)
        with open(savepath+"/"+slug+".json", "w") as write_file:
            json.dump(recipe, write_file, indent=4)
        if img != None:
            with open(savepath+"/"+slug+".jp2", "wb") as f:
                f.write(img)
    if do_image:
        make_image(driver, slug, savepath) # makes a screenshot internally



ATK_BASE = "https://www.americastestkitchen.com"

# Values for get_searches.py --sortby, mapped to the search page's "s" URL parameter
SORT_OPTIONS = {
    "relevance": None,                                  # site default
    "date": "everest_search_published_date_desc",       # "Most Recent"
    "popularity": "everest_search_avg_rating_desc",     # "Highest Rated"
    "rating": "everest_search_avg_rating_desc",
}

def normalize_search_url(page, sortby=None):
    """
    Bring an old-style search URL up to date and apply the sort order.

    The site renamed its filter parameters from fR[field][0]=value to
    r[field][0]=value, and sorting is now the "s" parameter. Returns
    (url, is_search_page).
    """
    parts = urlsplit(page)
    if not parts.netloc:
        parts = urlsplit(urljoin(ATK_BASE, page))
    if not parts.path.rstrip('/').endswith('/search'):
        return (urlunsplit(parts), False)
    query = []
    for key, value in parse_qsl(parts.query, keep_blank_values=True):
        if key.startswith('fR['):
            key = 'r[' + key[3:]
        if key in ('s', 'p'):
            continue  # set below / by load_full_page
        query.append((key, value))
    sort_value = SORT_OPTIONS.get(sortby)
    has_text = any(k == 'q' and v.strip() for k, v in query)
    if sort_value and has_text:
        # The site's sorted views return only close matches for text searches
        # (e.g. 18 instead of 203 results), so keep relevance order there.
        print("  Note: not sorting by " + sortby + " because this search has search words; "
              "sorting would drop most results.")
    elif sort_value:
        query.insert(0, ('s', sort_value))
    return (urlunsplit(parts._replace(query=urlencode(query))), True)

def recipe_links(html):
    """Return the recipe page URLs linked from a page, without tracking parameters."""
    soup = BeautifulSoup(html, 'html.parser')
    links = []
    for a in soup.find_all('a', href=True):
        url = urljoin(ATK_BASE, a['href'])
        parts = urlsplit(url)
        if not re.match(r'^/recipes/\d+-[^/]+$', parts.path):
            continue  # also skips /print pages
        url = urlunsplit((parts.scheme, parts.netloc, parts.path, '', ''))
        if url not in links:
            links.append(url)
    return links

def _set_page(url, page):
    parts = urlsplit(url)
    query = [(k, v) for k, v in parse_qsl(parts.query, keep_blank_values=True) if k != 'p']
    if page > 1:
        query.append(('p', str(page)))
    return urlunsplit(parts._replace(query=urlencode(query)))

def _has_load_more(driver):
    return any(b.is_displayed() for b in
               driver.find_elements(By.CSS_SELECTOR, 'button[aria-label="Load More"]'))

def _wait_for_results(driver, timeout=30):
    """
    Wait for the client-side app to finish rendering the result list: until the
    number of recipe links has stayed the same for a few seconds.
    """
    deadline = time.time() + timeout
    last, stable = -1, 0
    while time.time() < deadline:
        count = len(driver.find_elements(By.CSS_SELECTOR, 'a[href*="/recipes/"]'))
        if count > 0 and count == last:
            stable += 1
            if stable >= 3:
                return
        else:
            stable = 0
        last = count
        time.sleep(1)

def load_full_page(driver, url, max_page=1000):
    """
    Load a search page with all of its results showing.

    "Load More" on the search page just adds ?p=N to the URL, and loading ?p=N
    directly shows every result up to page N. So instead of clicking the button
    over and over, keep doubling N until the button is gone.
    """
    print("Loading all recipes", end='', flush=True)
    page = 1
    driver.get(url)
    _wait_for_results(driver)
    close_popups(driver)
    count = len(recipe_links(driver.page_source))
    while _has_load_more(driver) and page < max_page:
        page = min(page * 2, max_page)
        print('.', end='', flush=True)
        driver.get(_set_page(url, page))
        _wait_for_results(driver)
        new_count = len(recipe_links(driver.page_source))
        if new_count <= count and page > 2:
            break  # the site stopped returning more results
        count = new_count
    print("\n", flush=True)

def save_recipes(driver, search_result, do_image, do_json, sortby, savepath):
    url, is_search = normalize_search_url(search_result, sortby)
    if is_search:
        if 'search_browse_slugs' in url:
            print("  Note: the site no longer supports filtering search by cookbook "
                  "(search_browse_slugs); that filter is ignored.")
        load_full_page(driver, url)
    else:
        # Cookbook (/books/... -> /collections/books/...) and other collection
        # pages show a fixed list of recipes with no "Load More".
        try:
            driver.get(url)
        except Exception as e:
            print(e)
        _wait_for_results(driver)
        if '/collections/books/' in driver.current_url:
            print("  Note: cookbook pages now list only the book's featured recipes.")

    links = recipe_links(driver.page_source)
    length = len(links)
    print("Found {0} recipes".format(length))
    digits = len(str(length))

    for curr, link in enumerate(links, start=1):
        slug = basename(link)
        json_done = os.path.exists(os.path.join(savepath, slug + ".json"))
        image_done = os.path.exists(os.path.join(savepath, slug + ".png"))
        if (not do_json or json_done) and (not do_image or image_done):
            print("Already fetched " + slug)
            continue

        print('{0} / {1} | {2}'.format(str(curr).zfill(digits), length, link))
        try:
            save_one_recipe(driver, link, do_image and not image_done,
                            do_json and not json_done, savepath)
        except Exception as e:
            print("  Couldn't save " + link + ": " + str(e))
